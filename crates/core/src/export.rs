    #[test]
    fn constraint_briefing_renders_applied_rules_and_conflicts() {
        use crate::model::{Conflict, ConflictKind, Decision, RuleMatch};

        let r = rule("c1", "Use tabs", 100, "Indent with tabs.");
        let applied = RuleMatch {
            rule: r,
            decision: Decision::Applied,
            reasons: vec![],
            superseded_by: None,
            warnings: vec!["editorconfig says spaces".into()],
        };
        let resolution = Resolution {
            applied: vec![applied],
            trace: vec![],
            conflicts: vec![Conflict {
                kind: ConflictKind::RuleVsCode,
                rule_ids: vec!["c1".into()],
                description: "tabs vs spaces".into(),
                resolution_hint: Some("ask the user".into()),
            }],
        };
        let brief = render_constraint_briefing(&resolution, "ship it");
        assert!(brief.contains("# Agent Control"), "{brief}");
        assert!(brief.contains("## Use tabs (c1)"), "{brief}");
        assert!(brief.contains("Indent with tabs."), "{brief}");
        assert!(
            brief.contains("> Warning: editorconfig says spaces"),
            "{brief}"
        );
        assert!(brief.contains("tabs vs spaces"), "{brief}");
        assert!(brief.contains("(hint: ask the user)"), "{brief}");
        assert!(brief.contains("## Task"), "{brief}");
        assert!(brief.contains("ship it"), "{brief}");

        // Nothing applicable and no task → empty briefing (the hook then injects nothing).
        let empty = Resolution {
            applied: vec![],
            trace: vec![],
            conflicts: vec![],
        };
        assert_eq!(render_constraint_briefing(&empty, ""), "");
    }

