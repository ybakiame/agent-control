//! Point each harness's native entry point at the live rule files in `.agent-control`.
//!
//! The managed block is a *static pointer*, not a copy of the rules: it tells the agent to read the
//! enabled contract/constraint rules in `.agent-control/rules/` (and preferences in
//! `~/.agent-control/rules/user/`), or to call MCP `get_applicable_rules` for precise resolution.
//! Because the body never varies with the rule set, re-export is byte-idempotent and a rule edit
//! never makes the block stale — the agent always reads the current files. The block embeds a
//! *format version* (`BLOCK_FORMAT`) so drift means "missing block or an older block format", e.g. a
//! legacy v1 full-text block that should be migrated. Everything outside the markers is the user's
//! and is never touched; `remove_managed_block` revokes the block while preserving that prose.

use std::path::{Path, PathBuf};

use anyhow::{Result, bail};

use crate::config::DataLayout;
use crate::model::{
    AssuranceTier, ConstraintAssurance, Decision, HandoffBundle, Resolution, RuleMatch, Scope,
};

pub const BLOCK_BEGIN: &str = "<!-- agent-control:begin -->";
pub const BLOCK_END: &str = "<!-- agent-control:end -->";

/// Version of the managed-block format. v1 inlined the full rule text plus a ruleset hash; v2 is a
/// static pointer at the live rule files plus this version marker. Bump when the block layout changes
/// so `export_drift` can flag older blocks for migration.
pub const BLOCK_FORMAT: u32 = 2;

/// Prefix of the in-block format-version line. `read_exported_format` parses the number after it.
pub const FORMAT_PREFIX: &str = "<!-- agent-control:block-format:";

/// Frontmatter for the dedicated Cursor rule file. It sits *outside* the managed block, so a user
/// who tweaks it keeps their edits across re-exports.
pub const CURSOR_FRONTMATTER: &str = "\
---
description: Agent Control binding project contracts (pointer)
alwaysApply: true
---
";

const GENERATED_NOTE: &str = "<!-- Generated by Agent Control. This block points at .agent-control; manage rules in the console, not here. -->";

