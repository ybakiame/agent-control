//! Compile the binding rule set into each harness's native entry point.
//!
//! Project contracts are injected into a *managed block* inside the project's `AGENTS.md` /
//! `CLAUDE.md` and a dedicated `.cursor/rules/agent-control.mdc`; user preferences go to the
//! user-global `~/.claude/CLAUDE.md`. Everything outside the block markers is the user's and is
//! never touched, so a hand-written `AGENTS.md` is safe to export into. The block is the management
//! boundary: re-export replaces only the block, preserving frontmatter and prose around it.

use std::path::PathBuf;

use anyhow::{Result, bail};
use sha2::{Digest, Sha256};

use crate::model::Rule;

pub const BLOCK_BEGIN: &str = "<!-- agent-control:begin -->";
pub const BLOCK_END: &str = "<!-- agent-control:end -->";

/// Prefix of the in-block ruleset hash line. The hash is the sha256 of the rendered body, so drift
/// means exactly "re-exporting would change this file" — never a false alarm from reformatting.
pub const RULESET_PREFIX: &str = "<!-- agent-control:ruleset sha256:";

/// Frontmatter for the dedicated Cursor rule file. It sits *outside* the managed block, so a user
/// who tweaks it keeps their edits across re-exports.
pub const CURSOR_FRONTMATTER: &str = "\
---
description: Agent Control binding project contracts (generated)
alwaysApply: true
---
";

const GENERATED_NOTE: &str = "<!-- Generated by Agent Control. Edits inside this block are overwritten on re-export; manage rules in the console, not here. -->";

/// One exported file and what happened to it.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct TargetOutcome {
    pub path: PathBuf,
    /// created | updated | unchanged
    pub action: String,
}

/// Result of compiling the binding set to native entry points.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct ExportReport {
    pub project_path: PathBuf,
    pub project_rules: usize,
    pub user_rules: usize,
    pub targets: Vec<TargetOutcome>,
}

/// Drift state of one exported file: whether it exists, the hash embedded in it (if any), the hash
/// of the body we would render now, and whether they differ. A missing file is not "stale" — it was
/// simply never exported.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct TargetDrift {
    pub path: PathBuf,
    pub exists: bool,
    pub exported_hash: Option<String>,
    pub current_hash: String,
    pub stale: bool,
}

/// Result of comparing the exported managed blocks against the current binding set. `stale` is true
/// when any existing target's embedded hash differs from what we would render now. Detection only:
/// the caller prompts a re-export, never rewrites files silently.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct DriftReport {
    pub project_path: PathBuf,
    pub stale: bool,
    pub targets: Vec<TargetDrift>,
}

/// Render the inner markdown body for a rule set (no block markers). Rules are ordered by priority
/// descending then id, so the output is deterministic and idempotent across re-exports.
pub fn render_body(rules: &[Rule], heading: &str) -> String {
    let mut sorted: Vec<&Rule> = rules.iter().collect();
    sorted.sort_by(|a, b| b.priority.cmp(&a.priority).then(a.id.cmp(&b.id)));

    let mut out = format!("## {heading}\n\n");
    if sorted.is_empty() {
        out.push_str("_No binding rules._\n");
        return out;
    }
    for rule in sorted {
        out.push_str(&format!(
            "### {} · `{}` · {} · priority {}\n\n",
            rule.title, rule.id, rule.kind, rule.priority
        ));
        if !rule.applies_to.is_universal() {
            out.push_str(&format!("_Applies to: {}_\n\n", applies_summary(rule)));
        }
        out.push_str(rule.content.trim());
        out.push_str("\n\n");
    }
    out
}

fn applies_summary(rule: &Rule) -> String {
    let a = &rule.applies_to;
    let mut parts = Vec::new();
    if !a.agents.is_empty() {
        parts.push(format!("agents {:?}", a.agents));
    }
    if !a.paths.is_empty() {
        parts.push(format!("paths {:?}", a.paths));
    }
    if !a.languages.is_empty() {
        parts.push(format!("languages {:?}", a.languages));
    }
    if !a.tasks.is_empty() {
        parts.push(format!("tasks {:?}", a.tasks));
    }
    parts.join(", ")
}

/// sha256 of a rendered body. Embedded in the block so a reader can detect drift without re-resolving
/// rules: the file is stale iff this differs from the hash of the body we would render now.
pub fn content_hash(body: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(body.as_bytes());
    hex::encode(hasher.finalize())
}

/// Wrap a rendered body in the managed-block markers plus a generated-note and the ruleset hash. The
/// block carries no trailing newline: the file's terminating newline is added by `upsert_managed_block`
/// so that it survives as the suffix after the end marker and re-export stays byte-idempotent.
pub fn wrap_block(body: &str) -> String {
    format!(
        "{BLOCK_BEGIN}\n{GENERATED_NOTE}\n{RULESET_PREFIX}{} -->\n{body}{BLOCK_END}",
        content_hash(body)
    )
}

/// Read the ruleset hash embedded in an exported file's managed block, if present. Returns `None`
/// for a file with no block or a block written before hash embedding (treated as stale on compare).
pub fn read_exported_hash(existing: &str) -> Option<String> {
    let start = existing.find(RULESET_PREFIX)? + RULESET_PREFIX.len();
    let rest = &existing[start..];
    let end = rest.find(" -->")?;
    let hash = rest[..end].trim();
    if hash.is_empty() {
        None
    } else {
        Some(hash.to_string())
    }
}

/// Insert or replace the managed block in `existing`, preserving everything outside it. A file with
/// no block gets one appended (newline-terminated); an empty file becomes just the block. A lone
/// begin/end marker is a malformed state and errors rather than risking corruption.
pub fn upsert_managed_block(existing: &str, block: &str) -> Result<String> {
    let begin = existing.find(BLOCK_BEGIN);
    let end = existing.find(BLOCK_END);
    match (begin, end) {
        (Some(b), Some(e)) => {
            if e < b {
                bail!("malformed agent-control block: end marker precedes begin");
            }
            let after = e + BLOCK_END.len();
            Ok(format!("{}{}{}", &existing[..b], block, &existing[after..]))
        }
        (None, None) => {
            if existing.trim().is_empty() {
                Ok(format!("{block}\n"))
            } else {
                Ok(format!("{}\n\n{block}\n", existing.trim_end()))
            }
        }
        _ => bail!("malformed agent-control block: found only one of begin/end markers"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{AppliesTo, RuleKind, RuleSource, Scope, SourceKind};
    use chrono::Utc;

    fn rule(id: &str, title: &str, priority: i32, content: &str) -> Rule {
        Rule {
            id: id.into(),
            version: 1,
            title: title.into(),
            topic: None,
            content: content.into(),
            kind: RuleKind::Contract,
            scope: Scope::Project,
            source: RuleSource {
                kind: SourceKind::Project,
                file_path: None,
                author: None,
                created_at: Utc::now(),
                origin: None,
            },
            priority,
            applies_to: AppliesTo::default(),
            tags: vec![],
            conflicts_with: vec![],
            code_checks: vec![],
            enabled: true,
            enforcement: Default::default(),
            checksum: String::new(),
        }
    }

    #[test]
    fn render_body_orders_by_priority_then_id() {
        let rules = vec![
            rule("b-low", "B", 50, "b body"),
            rule("a-high", "A", 200, "a body"),
            rule("c-high", "C", 200, "c body"),
        ];
        let body = render_body(&rules, "Project contracts");
        let a = body.find("a-high").unwrap();
        let c = body.find("c-high").unwrap();
        let b = body.find("b-low").unwrap();
        assert!(a < c && c < b, "priority desc then id asc:\n{body}");
    }

    #[test]
    fn render_body_empty_and_applies_to() {
        assert!(render_body(&[], "Personal preferences").contains("No binding rules"));
        let mut r = rule("x", "X", 100, "x body");
        r.applies_to.paths = vec!["src/**".into()];
        let body = render_body(&[r], "Project contracts");
        assert!(body.contains("Applies to:"), "{body}");
        assert!(body.contains("src/**"), "{body}");
    }

    #[test]
    fn upsert_into_empty_file_is_just_block() {
        let block = wrap_block("## H\n\nbody\n\n");
        let out = upsert_managed_block("", &block).unwrap();
        assert_eq!(out, format!("{block}\n"));
    }

    #[test]
    fn upsert_appends_and_preserves_existing_prose() {
        let existing = "# My hand-written AGENTS.md\n\nKeep me.\n";
        let block = wrap_block("## Contracts\n\nrule body\n\n");
        let out = upsert_managed_block(existing, &block).unwrap();
        assert!(out.starts_with("# My hand-written AGENTS.md\n\nKeep me.\n"));
        assert!(out.contains(BLOCK_BEGIN) && out.contains(BLOCK_END));
        assert!(out.contains("rule body"));
    }

    #[test]
    fn upsert_replaces_only_block_preserving_outside() {
        let before = "# Title\n\nintro prose\n\n";
        let after = "\n\n## User section\n\nuser prose\n";
        let v1 = wrap_block("## Contracts\n\nold body\n\n");
        let existing = format!("{before}{v1}{after}");
        let v2 = wrap_block("## Contracts\n\nnew body\n\n");
        let out = upsert_managed_block(&existing, &v2).unwrap();
        assert!(out.starts_with(before), "prefix preserved:\n{out}");
        assert!(out.ends_with(after), "suffix preserved:\n{out}");
        assert!(out.contains("new body") && !out.contains("old body"));
        assert_eq!(out.matches(BLOCK_BEGIN).count(), 1);
    }

    #[test]
    fn upsert_is_idempotent() {
        let block = wrap_block("## Contracts\n\nbody\n\n");
        let once = upsert_managed_block("# Doc\n", &block).unwrap();
        let twice = upsert_managed_block(&once, &block).unwrap();
        assert_eq!(once, twice);
    }

    #[test]
    fn upsert_preserves_cursor_frontmatter_outside_block() {
        let existing = format!(
            "{CURSOR_FRONTMATTER}{}",
            wrap_block("## Contracts\n\nv1\n\n")
        );
        let out = upsert_managed_block(&existing, &wrap_block("## Contracts\n\nv2\n\n")).unwrap();
        assert!(out.starts_with(CURSOR_FRONTMATTER));
        assert!(out.contains("v2") && !out.contains("v1"));
    }

    #[test]
    fn upsert_rejects_malformed_single_marker() {
        let only_begin = format!("prose\n{BLOCK_BEGIN}\ninner");
        assert!(upsert_managed_block(&only_begin, "block").is_err());
        let only_end = format!("prose\n{BLOCK_END}\ninner");
        assert!(upsert_managed_block(&only_end, "block").is_err());
        let reversed = format!("{BLOCK_END}\n{BLOCK_BEGIN}");
        assert!(upsert_managed_block(&reversed, "block").is_err());
    }

    #[test]
    fn wrap_block_embeds_readable_hash() {
        let body = "## Contracts\n\nbody\n\n";
        let block = wrap_block(body);
        assert!(block.contains(RULESET_PREFIX));
        assert_eq!(
            read_exported_hash(&block).as_deref(),
            Some(content_hash(body).as_str())
        );
    }

    #[test]
    fn content_hash_is_stable_and_sensitive() {
        assert_eq!(content_hash("a"), content_hash("a"));
        assert_ne!(content_hash("a"), content_hash("b"));
    }

    #[test]
    fn read_exported_hash_absent_without_block() {
        assert_eq!(read_exported_hash("# plain doc\nno block here"), None);
        assert_eq!(read_exported_hash(""), None);
    }

    #[test]
    fn drift_reflects_body_change_not_reformat() {
        let body = "## Contracts\n\nrule body\n\n";
        let exported = wrap_block(body);
        // Same body re-rendered → same hash → not stale.
        assert_eq!(
            read_exported_hash(&exported).as_deref(),
            Some(content_hash(body).as_str())
        );
        // Changed body → different hash → stale.
        let changed = "## Contracts\n\nnew rule body\n\n";
        assert_ne!(
            read_exported_hash(&exported).as_deref(),
            Some(content_hash(changed).as_str())
        );
    }
}
